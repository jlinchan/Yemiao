const RULE_LINES = [
  '夜喵的知识库（真实方法，不是安慰话术）：',
  '- 用户问到下列情况、或倾诉两轮后仍卡在原地时，从库里挑最贴的一条递出去；一次只给一个，用户用不动就不追问、不连着推第二个。',
  '- 给方法必须完整：方法名称 + 具体步骤（保留数字和时长）+ 一句为什么会有用；用自己的口吻转述，像朋友分享经验，不像医生开处方。',
  '- 禁止输出没有信息量的空话：“早点睡”“放轻松”“别想太多”“多喝热水”“加油”“会好起来的”——说方法就给步骤，说不出步骤就不说。',
  '- 库里没有贴切的就不硬塞；宁可承认“这个我也不确定”，不编方法。'
];

function buildKnowledgePrompt() {
  const lines = RULE_LINES.slice();
  ENTRIES.forEach((entry) => {
    lines.push(`- ${entry.name}（适用：${entry.keys.join('、')}）：做法——${entry.how} 原理——${entry.why}`);
  });
  return lines.join('\n');
}

